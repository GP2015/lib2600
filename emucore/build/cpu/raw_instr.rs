use strum::EnumCount;

#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
pub struct RawInstr {
    pub stem: RawStem,
    pub addr: RawAddrMode,
}

impl RawInstr {
    const fn default() -> Self {
        Self {
            stem: RawStem::Nop,
            addr: RawAddrMode::Impl,
        }
    }
}

// A->Impl, Rel->Imm
#[derive(Clone, Copy, Debug, EnumCount, Eq, Hash, PartialEq)]
pub enum RawAddrMode {
    Abs,
    AbsX,
    AbsY,
    Imm,
    Impl,
    Ind,
    XInd,
    IndY,
    Zpg,
    ZpgX,
    ZpgY,
}

